@router.post(
    "/llm/council",
    summary="Run Multi-Endpoint Free LLM Council + Anonymous Cross-Review + Dream-RSI Synthesis",
)
async def run_llm_council(request: CouncilRequest, raw_request: Request) -> dict[str, Any]:
    settings = get_settings()
    if request.endpoints:
        has_custom = any(
            isinstance(ep, LLMOverride) and (ep.base_url or ep.api_key or ep.extra_headers)
            for ep in request.endpoints
        )
        if has_custom:
            if settings.auth_enabled:
                await require_admin(raw_request)
            elif not settings.llm_byo_enabled:
                raise MetaSearchError(
                    ErrorCode.UNAUTHORIZED,
                    "Custom LLM endpoints in council require admin privileges or "
                    "LLM_BYO_ENABLED=true",
                    status_code=403,
                )
    gateway = deps.get_gateway()
    sources: list[dict[str, Any]] = []

    if request.chunks:
        included: list[tuple[int, Chunk]] = []
        for idx, item in enumerate(request.chunks, start=1):
            num = item.n or idx
            txt = item.content or item.text
            included.append(
                (
                    num,
                    Chunk(
                        id=item.chunk_id or f"council-chunk-{num}",
                        document_url=item.url,
                        source_title=item.title or item.url,
                        heading_path="",
                        position=num,
                        content=txt,
                        word_count=len(txt.split()),
                    ),
                )
            )
        sources = [{"url": c.url, "title": c.title, "domain": ""} for c in request.chunks]
    else:
        params = SearchParams(
            query=request.query,
            lang=request.lang,
            k=request.k,
            engines=request.engines,
            categories=request.categories,
            freshness_days=request.freshness_days,
            include_snippets=request.include_snippets,
            news=request.news,
        )
        ctx = await deps.get_answer_pipeline().prepare_context(
            params, budget=request.budget, domain=request.domain
        )
        raw_chunks = list(ctx.get("chunks") or [])  # type: ignore[arg-type]
        included = [
            (
                int(c["n"]),
                Chunk(
                    id=str(c.get("chunk_id") or f"chunk-{c['n']}"),
                    document_url=str(c["url"]),
                    source_title=str(c.get("title") or c["url"]),
                    heading_path=str(c.get("heading_path") or ""),
                    position=int(c["n"]),
                    content=str(c["content"]),
                    word_count=int(c.get("word_count") or len(str(c["content"]).split())),
                ),
            )
            for c in raw_chunks
        ]
        sources = list(ctx.get("sources") or [])  # type: ignore[arg-type]

    engine = DreamRSICouncilEngine(settings, gateway)
    coerced_eps = coerce_council_endpoints(request.endpoints) if request.endpoints else None
    try:
        result = await engine.run_council(
            request.query,
            included,
            endpoints=coerced_eps,
            domain=request.domain,
            enable_cross_review=request.enable_cross_review,
        )
    except LLMError as exc:
        raise MetaSearchError(ErrorCode.INTERNAL, str(exc)) from exc

    result["sources"] = sources
    return result


