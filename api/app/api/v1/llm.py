@router.post("/llm/test", summary="Test connectivity and latency of an LLM endpoint")
async def test_llm_connection(request: LLMTestRequest, raw_request: Request) -> dict[str, Any]:
    started = time.perf_counter()
    settings = get_settings()
    if request.llm and (request.llm.base_url or request.llm.api_key or request.llm.extra_headers):
        if settings.auth_enabled:
            await require_admin(raw_request)
        elif not settings.llm_byo_enabled:
            raise MetaSearchError(
                ErrorCode.UNAUTHORIZED,
                "Custom LLM target test requires admin privileges or LLM_BYO_ENABLED=true",
                status_code=403,
            )
    gateway = deps.get_gateway()
    if hasattr(gateway, "with_override") and request.llm is not None:
        gateway = gateway.with_override(request.llm)
    target = (
        gateway.resolve_target()
        if hasattr(gateway, "resolve_target")
        else resolve_llm_target(
            get_settings(),
            runtime_override=get_runtime_llm_store().get_override(),
            request_override=request.llm,
        )
    )
    model = (
        request.llm.model
        if request.llm and request.llm.model
        else getattr(gateway, "default_quick_model", target.quick_model)
    )
    messages = [{"role": "user", "content": request.prompt}]
    try:
        parts: list[str] = []
        async for delta in gateway.stream(messages, model=model, max_tokens=32):
            if delta.text:
                parts.append(delta.text)
        latency_ms = int((time.perf_counter() - started) * 1000)
        return {
            "ok": True,
            "provider": target.provider,
            "model": model,
            "base_url": target.base_url,
            "reply": "".join(parts).strip(),
            "latency_ms": latency_ms,
        }
    except LLMError as exc:
        latency_ms = int((time.perf_counter() - started) * 1000)
        return {
            "ok": False,
            "provider": target.provider,
            "model": model,
            "base_url": target.base_url,
            "error": str(exc),
            "latency_ms": latency_ms,
        }


@router.post(
    "/context",
    summary="Prepare deduplicated, scraped, reranked RAG context for an external system's LLM",
)
async def build_external_llm_context(request: ContextRequest) -> dict[str, Any]:
    from app.core.admission import admit
    from app.core.budget import create_budget_for_route, use_budget

    budget = create_budget_for_route("context", timeout_ms=request.timeout_ms)
    async with admit("context"):
        with use_budget(budget):
            params = SearchParams(
                query=request.query,
                lang=request.lang,
                k=request.k,
                engines=request.engines,
                categories=request.categories,
                freshness_days=request.freshness_days,
                include_snippets=request.include_snippets,
                news=request.news,
                timeout_ms=request.timeout_ms,
            )
            return await deps.get_answer_pipeline().prepare_context(
                params, budget=request.budget, domain=request.domain
            )


@router.post(
    "/citations/validate",
    summary="Validate [n] citations in an answer generated by an external system's LLM",
)
async def validate_external_llm_citations(request: CitationValidateRequest) -> dict[str, Any]:
    included: list[tuple[int, Chunk]] = []
    for idx, item in enumerate(request.chunks, start=1):
        num = item.n or idx
        txt = item.content or item.text
        chunk = Chunk(
            id=item.chunk_id or f"ext-chunk-{num}",
            document_url=item.url,
            source_title=item.title or item.url,
            heading_path="",
            position=num,
            content=txt,
            word_count=len(txt.split()),
        )
        included.append((num, chunk))
    check = validate_citations(request.answer_md, included)
    return {
        "validated_answer_md": check.text,
        "citations": [
            {"n": c.n, "url": c.url, "title": c.title, "chunk_id": c.chunk_id}
            for c in check.citations
        ],
        "invalid_markers": check.invalid_markers,
    }
