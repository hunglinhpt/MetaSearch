"""LLM provider configuration, Multi-Endpoint Dream-RSI Council & Cross-Review,
Universal Domain Intelligence, and External System LLM integration endpoints.

Endpoints:
- ``GET  /v1/llm/providers``         -> Catalog of 20 presets (OpenRouter Free, nejib1/Free-LLM,
                                        awesome-freellm-apis) + active config.
- ``GET  /v1/llm/config``            -> Active LLM configuration (masked keys).
- ``PATCH /v1/llm/config``           -> Hot-update LLM provider/model/base_url/api_key/headers.
- ``POST /v1/llm/config/reset``      -> Reset runtime LLM overrides back to .env defaults.
- ``POST /v1/llm/test``              -> Probe LLM connectivity & latency.
- ``POST /v1/llm/council``           -> Run Multi-Endpoint Free LLM Council + Anonymous
                                        Cross-Review + Chairman Verdict + Dream-RSI Replay.
- ``PATCH /v1/llm/council/endpoints``-> Hot-configure the Council's multi-endpoint panel.
- ``GET  /v1/llm/dream-rsi/state``   -> Inspect Dream-RSI Replay World & evolved policies.
- ``POST /v1/llm/dream-rsi/reset``   -> Reset Dream-RSI trajectory store.
- ``GET  /v1/domains``               -> List Universal Multi-Domain Deep Intelligence packs
                                        (Financial Flagship Pilot + 7 domain packs).
- ``POST /v1/domains/analyze``       -> Preview domain decomposition & forensic rubric for a query.
- ``POST /v1/context``               -> Context-only RAG pipeline for external systems with their
                                        own internal LLM.
- ``POST /v1/citations/validate``    -> Validate [n] citations in an answer generated by an
                                        external system's LLM.
"""

