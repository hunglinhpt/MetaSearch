"""LLM provider configuration, connectivity probe, and External System LLM integration
endpoints.

Endpoints:
- ``GET  /v1/llm/providers``       -> Catalog of presets (OpenRouter Free, Pollinations,
                                      Gemini, Groq, Cerebras, Mistral, GitHub Models,
                                      HuggingFace, Ollama, Custom BYO-LLM) + active config.
- ``GET  /v1/llm/config``          -> Active LLM configuration (masked keys).
- ``PATCH /v1/llm/config``         -> Hot-update LLM provider/model/base_url/api_key/headers.
- ``POST /v1/llm/config/reset``    -> Reset runtime LLM overrides back to .env defaults.
- ``POST /v1/llm/test``            -> Probe LLM connectivity & latency.
- ``POST /v1/context``             -> Context-only RAG pipeline for external systems with their
                                      own internal LLM (returns numbered context_md, messages,
                                      chunks, and sources without calling an internal LLM).
- ``POST /v1/citations/validate``  -> Validate [n] citations in an answer generated by an
                                      external system's LLM against MetaSearch context chunks.
"""

from __future__ import annotations

import time
from typing import Any

from fastapi import APIRouter, Depends
from pydantic import BaseModel, Field

from app.api import deps
from app.api.v1.schemas import SearchRequest
from app.config import get_settings
from app.core.auth import require_admin
from app.extraction.chunker import Chunk
from app.llm.citations import validate_citations
from app.llm.gateway import LLMError
from app.llm.providers import (
    LLM_PROVIDER_PRESETS,
    LLMOverride,
    get_runtime_llm_store,
    mask_api_key,
    resolve_llm_target,
)
from app.orchestration.pipeline import SearchParams

router = APIRouter(tags=["llm"])


class LLMTestRequest(BaseModel):
    llm: LLMOverride | None = None
    prompt: str = Field(
        default="Reply with the single word: READY",
        min_length=1,
        max_length=500,
    )


class ContextRequest(SearchRequest):
    budget: int | None = Field(default=None, ge=200, le=50_000)


class ContextChunkInput(BaseModel):
    n: int = Field(ge=1, le=999)
    url: str = Field(min_length=1, max_length=2000)
    title: str = ""
    chunk_id: str = ""
    content: str = ""


class CitationValidateRequest(BaseModel):
    answer_md: str = Field(min_length=1, max_length=200_000)
    chunks: list[ContextChunkInput] = Field(min_length=1, max_length=200)


def _active_config_summary() -> dict[str, Any]:
    settings = get_settings()
    store = get_runtime_llm_store()
    override = store.get_override()
    target = resolve_llm_target(settings, runtime_override=override)
    preset = LLM_PROVIDER_PRESETS.get(target.provider, LLM_PROVIDER_PRESETS["custom"])
    has_key = bool(target.api_key)
    return {
        "provider": target.provider,
        "provider_name": preset.name,
        "protocol": target.protocol,
        "base_url": target.base_url,
        "quick_model": target.quick_model,
        "report_model": target.report_model,
        "is_free": preset.is_free or target.quick_model == "openrouter/free",
        "requires_api_key": preset.requires_api_key,
        "has_api_key": has_key,
        "masked_api_key": mask_api_key(target.api_key),
        "fallback_provider": target.fallback_provider,
        "fallback_models": target.fallback_models,
        "extra_headers_keys": sorted(target.extra_headers.keys()),
        "has_runtime_override": override is not None,
    }


@router.get("/llm/providers", summary="List free, local, and BYO-LLM provider presets")
async def list_llm_providers() -> dict[str, Any]:
    settings = get_settings()
    store = get_runtime_llm_store()
    override = store.get_override()
    providers_out: list[dict[str, Any]] = []
    for preset in LLM_PROVIDER_PRESETS.values():
        resolved = resolve_llm_target(
            settings,
            runtime_override=override,
            request_override=LLMOverride(provider=preset.id),
        )
        configured = (not preset.requires_api_key) or bool(resolved.api_key)
        providers_out.append(
            {
                "id": preset.id,
                "name": preset.name,
                "protocol": preset.protocol,
                "base_url": preset.base_url,
                "default_quick_model": preset.default_quick_model,
                "default_report_model": preset.default_report_model,
                "is_free": preset.is_free,
                "requires_api_key": preset.requires_api_key,
                "env_key_name": preset.env_key_name,
                "signup_url": preset.signup_url,
                "docs_url": preset.docs_url,
                "description": preset.description,
                "recommended_models": preset.recommended_models,
                "configured": configured,
            }
        )
    return {
        "active": _active_config_summary(),
        "providers": providers_out,
        "external_integration": {
            "byo_llm_description": (
                "Pass an `llm` override object in POST /v1/answer or POST /v1/research, "
                "or update server-wide via PATCH /v1/llm/config."
            ),
            "context_only_endpoint": "/v1/context",
            "citation_validation_endpoint": "/v1/citations/validate",
        },
    }


@router.get("/llm/config", summary="Get active LLM configuration")
async def get_llm_config() -> dict[str, Any]:
    return _active_config_summary()


@router.patch(
    "/llm/config",
    dependencies=[Depends(require_admin)],
    summary="Hot-update active LLM provider, model, base_url, or API key",
)
async def patch_llm_config(request: LLMOverride) -> dict[str, Any]:
    get_runtime_llm_store().update(request)
    return _active_config_summary()


@router.post(
    "/llm/config/reset",
    dependencies=[Depends(require_admin)],
    summary="Reset runtime LLM configuration back to environment defaults",
)
async def reset_llm_config() -> dict[str, Any]:
    get_runtime_llm_store().reset()
    return _active_config_summary()


@router.post("/llm/test", summary="Test connectivity and latency of an LLM endpoint")
async def test_llm_connection(request: LLMTestRequest) -> dict[str, Any]:
    started = time.perf_counter()
    gateway = deps.get_gateway()
    if hasattr(gateway, "with_override") and request.llm is not None:
        gateway = gateway.with_override(request.llm)
    target = (
        gateway.resolve_target()
        if hasattr(gateway, "resolve_target")
        else resolve_llm_target(
            get_settings(),
            runtime_override=get_runtime_llm_store().get_override(),
            request_override=request.llm,
        )
    )
    model = (
        request.llm.model
        if request.llm and request.llm.model
        else getattr(gateway, "default_quick_model", target.quick_model)
    )
    messages = [{"role": "user", "content": request.prompt}]
    try:
        parts: list[str] = []
        async for delta in gateway.stream(messages, model=model, max_tokens=32):
            if delta.text:
                parts.append(delta.text)
        latency_ms = int((time.perf_counter() - started) * 1000)
        return {
            "ok": True,
            "provider": target.provider,
            "model": model,
            "base_url": target.base_url,
            "reply": "".join(parts).strip(),
            "latency_ms": latency_ms,
        }
    except LLMError as exc:
        latency_ms = int((time.perf_counter() - started) * 1000)
        return {
            "ok": False,
            "provider": target.provider,
            "model": model,
            "base_url": target.base_url,
            "error": str(exc),
            "latency_ms": latency_ms,
        }


@router.post(
    "/context",
    summary="Prepare deduplicated, scraped, reranked RAG context for an external system's LLM",
)
async def build_external_llm_context(request: ContextRequest) -> dict[str, Any]:
    params = SearchParams(
        query=request.query,
        lang=request.lang,
        k=request.k,
        engines=request.engines,
        categories=request.categories,
        freshness_days=request.freshness_days,
        include_snippets=request.include_snippets,
        news=request.news,
    )
    return await deps.get_answer_pipeline().prepare_context(params, budget=request.budget)


@router.post(
    "/citations/validate",
    summary="Validate [n] citations in an answer generated by an external system's LLM",
)
async def validate_external_llm_citations(request: CitationValidateRequest) -> dict[str, Any]:
    included: list[tuple[int, Chunk]] = []
    for item in request.chunks:
        chunk = Chunk(
            id=item.chunk_id or f"ext-chunk-{item.n}",
            document_url=item.url,
            source_title=item.title or item.url,
            heading_path="",
            position=item.n,
            content=item.content,
            word_count=len(item.content.split()),
        )
        included.append((item.n, chunk))
    check = validate_citations(request.answer_md, included)
    return {
        "validated_answer_md": check.text,
        "citations": [
            {"n": c.n, "url": c.url, "title": c.title, "chunk_id": c.chunk_id}
            for c in check.citations
        ],
        "invalid_markers": check.invalid_markers,
    }
